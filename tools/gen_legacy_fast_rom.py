"""Array form of the previous engine's wavetable ROM, for fast simulation.

Reads src/piano_dual_wavetable.v (a 256 entry `case`) and writes
sim/models/piano_dual_wavetable_fast.v with the same module name, ports and
timing.  Only used by sim/tb/tb_legacy_voice.v to render the old piano sound
for the A/B comparison.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "..", "src", "piano_dual_wavetable.v"), encoding="utf-8").read()
rows = re.findall(r"8'd(\d+):\s*begin\s*low_sample\s*<=\s*(-?)\s*24'sd(\d+);\s*high_sample\s*<=\s*(-?)\s*24'sd(\d+);", src)
assert len(rows) == 256, len(rows)
out = ["/* GENERATED by tools/gen_legacy_fast_rom.py from src/piano_dual_wavetable.v (simulation only) */",
       "module piano_dual_wavetable (", "    input  wire              clk,", "    input  wire [7:0]        addr,",
       "    output reg signed [23:0] low_sample,", "    output reg signed [23:0] high_sample", ");", "",
       "reg signed [23:0] lo [0:255];", "reg signed [23:0] hi [0:255];", "", "initial begin"]
for a, s1, v1, s2, v2 in rows:
    out.append("    lo[%s] = %s24'sd%s; hi[%s] = %s24'sd%s;" % (a, s1, v1, a, s2, v2))
out += ["end", "", "always @(posedge clk) begin", "    low_sample  <= lo[addr];", "    high_sample <= hi[addr];", "end", "",
        "endmodule", ""]
open(os.path.join(HERE, "..", "sim", "models", "piano_dual_wavetable_fast.v"), "w", newline="\n").write("\n".join(out))
print("wrote sim/models/piano_dual_wavetable_fast.v (%d entries)" % len(rows))
