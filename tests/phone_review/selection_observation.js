'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const {createSelection}=require(path.resolve(__dirname,'../../firmware/remote_music_ble/shouji/app.js'));
const selection=createSelection();
selection.actual({stateValid:true,mode:0,timbre:0,switching:false,fault:false});
selection.actual({stateValid:true,mode:0,timbre:3,switching:false,fault:false});
assert.equal(selection.groups.timbre.actual,3);
assert.equal(selection.groups.timbre.desired,0);
assert.equal(selection.groups.timbre.applied,false);
console.log('OBSERVED external timbre change: actual=3(guitar), desired=0(piano), applied=false. The actual-state text updates; selection highlight retains the previous target. Production UI unchanged.');
